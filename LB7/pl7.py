import random  # Імпортуємо модуль для вибору випадкових відповідей

# Словник відповідей
responses = {
    "привіт": ["Привіт!", "Доброго дня!", "Вітаю!"],
    "як справи": ["У мене все добре! А у вас?", "Чудово! Як ваш день?", "Нормально, дякую."],
    "що ти вмієш": ["Я можу відповідати на ваші питання", "Поки що я не дуже розумний, але я навчаюсь!"],
    "бувай": ["До зустрічі!", "Бувайте", "Щасливо"]
}

def chat_bot():
    print("Привіт! Я розумний бот. Запитайте мене про щось!")

    while True:
        user_input = input("Ви: ").lower()  # Отримуємо введення і переводимо у нижній регістр

        # Перевіряємо, чи є ключове слово у введенні користувача
        for key in responses.keys():
            if key in user_input:
                print("Бот:", random.choice(responses[key]))  # Випадкова відповідь зі списку
                if key == "бувай":
                    return  # Вихід із програми
                break
        else:
            print("Бот: Вибачте, я поки що цього не розумію. Спробуйте щось інше.")

chat_bot()